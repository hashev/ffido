#!/usr/bin/env python3
"""Record the exact instrumented packages and compatible OpenSSL for CMake."""
import argparse
import pathlib
import subprocess
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--mode', choices=['tsan', 'asan-ubsan'], required=True)
parser.add_argument('--prefix', type=pathlib.Path, required=True)
parser.add_argument('--openssl-root', type=pathlib.Path, required=True)
parser.add_argument('--ssl', type=pathlib.Path, required=True)
parser.add_argument('--crypto', type=pathlib.Path, required=True)
args = parser.parse_args()
prefix = args.prefix.resolve()
values = {'Protobuf_DIR': prefix/'lib/cmake/protobuf', 'gRPC_DIR': prefix/'lib/cmake/grpc',
          'absl_DIR': prefix/'lib/cmake/absl', 'OPENSSL_ROOT_DIR': args.openssl_root.resolve(),
          'OPENSSL_INCLUDE_DIR': args.openssl_root.resolve()/'include',
          'OPENSSL_SSL_LIBRARY': args.ssl.resolve(), 'OPENSSL_CRYPTO_LIBRARY': args.crypto.resolve()}
for library in ('protobuf', 'grpc', 'absl_synchronization'):
    candidates = [prefix/'lib'/f'lib{library}.so', prefix/'lib'/f'lib{library}.dylib']
    path = next((path for path in candidates if path.is_file()), None)
    if path is None:
        raise SystemExit(f'Required instrumented library missing: {library}')
    symbols = subprocess.run(['nm', '-u', str(path)], check=True, text=True, capture_output=True).stdout
    markers = ('__tsan_read', '__tsan_write') if args.mode == 'tsan' else ('__asan_report_load', '__asan_report_store')
    if not any(marker in symbols for marker in markers):
        raise SystemExit(f'Library has no matching sanitizer memory instrumentation: {library}')
optional = prefix/'lib/cmake/utf8_range'
if optional.exists():
    values['utf8_range_DIR'] = optional
for key, path in values.items():
    if not path.exists():
        raise SystemExit(f'Required dependency path missing: {key}')
lines = ['# Generated by the isolated sanitizer dependency build.']
for key, path in values.items():
    delimiter = '='
    while ']'+delimiter+']' in str(path):
        delimiter += '='
    lines.append(f'set({key} [{delimiter}[{path}]{delimiter}] CACHE PATH "Sanitizer dependency" FORCE)')
(prefix/f'ffido-{args.mode}-cache.cmake').write_text('\n'.join(lines)+'\n')
